//! scaffold — draft a schema-valid spine from the committed census.
//!
//! `scaffold <letter>` writes a grammar-valid one-leg skeleton into the
//! declared spine directory and refuses an existing target (70: the draft
//! never clobbers authored spine content). With the census readable it also
//! reports the census door ids NO spine cites yet — the draft's starting
//! citation surface comes FROM the committed census, never from guesses.

use std::path::Path;

use crate::config::Profile;

/// Render the skeleton document for a one-letter journey id (UJ-X).
pub fn skeleton(letter: &str) -> Result<String, String> {
    let mut chars = letter.chars();
    let (Some(c), None) = (chars.next(), chars.next()) else {
        return Err(format!(
            "scaffold needs one letter for the journey id, got {letter:?} (grammar: UJ-A..UJ-Z)"
        ));
    };
    if !c.is_ascii_alphabetic() {
        return Err(format!(
            "scaffold journey letter must be A-Z, got {letter:?}"
        ));
    }
    let up = c.to_ascii_uppercase().to_string();
    Ok(format!(
        r#"# UJ-{up} spine — scaffold generated by journeyspec. Fill the citations before verify.
journey: UJ-{up}
title: Replace with the journey title
provenance: Replace with doc and lane cites
worlds:
  clean-slate:
    seed: 0
    description: Fresh EMPTY system, browser-only.
legs:
  - id: "1"
    given: Replace with the precondition state.
    when:
      ui: Replace with the browser-reachable action
      doors: []
    then:
      - Replace with the observable outcome.
    ledger: []
    proof: {{ web: null, tauri: null, android: null }}
    edges: []
    forks: []
    world: clean-slate
    status: RED
    # A non-GREEN leg must declare waits_on or verify fails (stale-open):
    # waits_on: ["mile <proof-cite>"]   # machine-resolved unblock
    # waits_on: ["dependency CAND-A1"]  # decision declaration only
"#
    ))
}

/// The target path for a drafted spine inside the declared spine dir.
pub fn target(root: &Path, profile: &Profile, letter: &str) -> std::path::PathBuf {
    root.join(&profile.journeys_dir)
        .join(format!("uj-{}.yaml", letter.to_ascii_lowercase()))
}

/// Draft one spine: returns Ok(path) or a refusal/message with its class.
/// Existing targets are refused as OPERATIONAL (never clobbered).
pub fn draft(root: &Path, profile: &Profile, letter: &str) -> Result<std::path::PathBuf, (i32, String)> {
    let text = skeleton(letter).map_err(|e| (crate::exit::USAGE, e))?;
    let path = target(root, profile, letter);
    if path.exists() {
        return Err((
            crate::exit::OPERATIONAL,
            format!(
                "refusing to overwrite existing spine {} — it carries authored content",
                path.display()
            ),
        ));
    }
    if let Some(dir) = path.parent()
        && let Err(e) = std::fs::create_dir_all(dir)
    {
        return Err((
            crate::exit::OPERATIONAL,
            format!("cannot create spine dir: {e}"),
        ));
    }
    std::fs::write(&path, &text)
        .map_err(|e| (crate::exit::OPERATIONAL, format!("cannot write spine: {e}")))?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn skeleton_is_a_valid_spine() {
        let text = skeleton("x").unwrap();
        let s: crate::spine::Spine = serde_yaml::from_str(&text).expect("skeleton parses");
        assert_eq!(s.journey, "UJ-X");
        assert!(crate::spine::validate(&s).is_empty());
        assert_eq!(s.legs.len(), 1);
    }

    #[test]
    fn bad_letters_are_usage_errors() {
        assert!(skeleton("xy").is_err());
        assert!(skeleton("1").is_err());
        assert!(skeleton("").is_err());
    }

    #[test]
    fn existing_target_is_refused_not_clobbered() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        let profile = Profile::default();
        let p = draft(root, &profile, "Q").unwrap();
        assert!(p.is_file());
        std::fs::write(&p, "# authored\n").unwrap();
        let (code, msg) = draft(root, &profile, "q").unwrap_err();
        assert_eq!(code, crate::exit::OPERATIONAL);
        assert!(msg.contains("refusing to overwrite"), "{msg}");
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "# authored\n");
    }
}
